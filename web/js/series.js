/* Ниже порога — --hypo, а не --low: число в шапке и кривая под ним говорят об
   одном и том же сахаре, и назвать его двумя цветами на одном экране значит
   заставить читателя гадать, какой из них про что. Оранжевый остался цветом
   предупреждений о молчании — сенсора в шапке и сборщика в подвале. */
/* Цвет отдельной отметки на кривой — кружка, а не отрезка. Отрезки красятся
   отсечением по линии порога, но точка лежит целиком по одну его сторону, и
   срезанный пополам кружок читался бы как ещё одно значение рядом. */
/* Снимок без mid — от сборщика, который ещё не публикует внутреннюю границу.
   Совпав с high, она гасит жёлтую зону, и страница читается по-старому, а не
   рисует NaN-полосы поверх графика. */
export function targetMid() {
    return state.snapshot.target.mid ?? state.snapshot.target.high;
}

export function readingColor(mgdl) {
    if (mgdl < state.snapshot.target.low) return readColor("--hypo", "#ff5b5b");
    if (mgdl > state.snapshot.target.high) return readColor("--high", "#f77e9b");
    if (mgdl > targetMid()) return readColor("--hyper", "#ffd166");
    return readColor("--accent", "#7eb8f7");
}

export function zoneColor(mgdl) {
    const { low, high } = state.snapshot.target;
    if (mgdl < low) return "var(--hypo)";
    if (mgdl > high) return "var(--high)";
    if (mgdl > targetMid()) return "var(--hyper)";
    return "var(--in-range)";
}

/* Цветная метка ряда. Одна на легенду и на строки в шапке: там и там она
   опознаёт один и тот же ряд, а собранная в двух местах порознь — однажды
   разойдётся, и контурный квадратик под графиком станет залитым над ним. */
export function seriesKey(series) {
    const key = document.createElement("span");
    // Флаги складываются, а не исключают друг друга: метка длинной ручки —
    // и контур, и кружок разом.
    const flags = [
        series.hollow && "legend__key--hollow",
        series.line && "legend__key--line",
        series.thick && "legend__key--thick",
        series.band && "legend__key--band",
        series.striped && "legend__key--striped",
        series.dashed && "legend__key--dashed",
        series.marker && "legend__key--marker",
    ].filter(Boolean);
    key.className = ["legend__key", ...flags].join(" ");
    // Контурная метка красится через currentColor — так одна и та же переменная
    // задаёт и заливку, и рамку.
    key.style.color = `var(${series.token})`;
    key.style.background = `var(${series.token})`;
    return key;
}
