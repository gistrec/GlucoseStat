/* Общий изменяемый стейт страницы. Раньше это были top-level `let` в
   app.js — в ES-модулях так нельзя: импортированный биндинг нельзя
   переприсвоить извне того модуля, где он объявлен. Мутировать поле
   объекта можно откуда угодно, поэтому весь стейт — поля одного `state`. */

/* Сколько приёмов показывать сразу и сколько добавлять кнопкой. Разбор читают
   с последнего, и десяти строк хватает на пару дней.

   Кнопка удлиняет не только таблицу: вместе со строками на оверлей приходят их
   кривые. Иначе за две недели он превращается в заливку, из которой медиана —
   единственное, ради чего он рисуется, — уже не читается. */
export const MEALS_PAGE = 10;

export const state = {
    snapshot: null,
    activeRange: "day",

    // Раскладка последней отрисовки: по ней работает наведение. Пересчитывать
    // её на каждое движение мыши — значит дублировать всю геометрию и однажды
    // разойтись с тем, что нарисовано.
    geometry: null,
    hoverTime: null,

    // Сколько приёмов раскрыто сейчас. Живёт между перерисовками: снимок
    // перечитывается раз в минуту, и сброс к десяти сворачивал бы список под
    // руками у того, кто только что его раскрыл.
    mealsShown: MEALS_PAGE,

    // Раскладка последней отрисовки оверлея и минута под указателем — та же
    // пара, что geometry и hoverTime у графика выше, и по той же причине:
    // считать геометрию заново на каждое движение мыши значит однажды
    // разойтись с тем, что нарисовано. Минута, а не момент времени: ось
    // оверлея — время от еды.
    overlayGeometry: null,
    overlayHoverMin: null,

    /* Какой приём подсвечен на оверлее. Закреплённый нажатием — состояние
       покоя, к которому подсветка возвращается; указатель и фокус поверх
       него только показывают, на что сейчас смотрят. Так строка под
       курсором всегда означает свою кривую на графике, а не иногда — в
       зависимости от того, закреплено ли что-то ещё. Приём опознаётся
       временем: оно уникально и переживает перерисовку таблицы, так что
       закрепление не слетает от обновления снимка.

       Указатель и фокус держатся порознь и решают последним словом: увести
       мышь со стола, не погасив кривую, выбранную с клавиатуры, — и
       наоборот. */
    hoveredMeal: null,
    focusedMeal: null,
    previewMeal: null,
    pinnedMeal: null,

    profileTzWarned: false,
    timezoneWarned: false,

    theme: "dark",
};
